    ' हो। यो संयोजनले ',
    CASE t.bhava_id
      WHEN 1 THEN 'आत्मजागरण र लग्नशुद्धि'
      WHEN 2 THEN 'धनमा सन्तोष र सत्कर्म'
      WHEN 3 THEN 'साहस र धैर्यसँग जोडिएको धार्मिक कार्य'
      WHEN 4 THEN 'कुलदेवता र परिवारको इष्टदेवताको पूजा'
      WHEN 5 THEN 'भक्ति, मन्त्रजप र सन्तानको संस्कार'
      WHEN 6 THEN 'शत्रु उपशमन र रोगबाट मुक्तिको प्रार्थना'
      WHEN 7 THEN 'जीवनसाथीसँगै धार्मिक कार्य र सामञ्जस्य'
      WHEN 8 THEN 'गुप्त साधना र आयुरक्षाको विधि'
      WHEN 9 THEN 'धर्म, गुरु र तीर्थसम्बन्धी आचरण'
      WHEN 10 THEN 'कर्म र धर्मको सन्तुलन'
      WHEN 11 THEN 'सत्संग र साधकसँगको सङ्गत'
      WHEN 12 THEN 'मोक्ष, मुक्ति र एकान्त साधना'
    END,
    'मा विशेष असर गर्दा साधकको आध्यात्मिक उन्नतिमा ठूलो महत्त्व पाउँछ। विशेष गरी ',
    CASE t.rashi_id
      WHEN 1 THEN 'नेतृत्व र पहलकदमी'
      WHEN 2 THEN 'संचय र स्थिरता'
      WHEN 3 THEN 'वाणी र सम्बन्ध'
      WHEN 4 THEN 'परिवार र सुरक्षा'
      WHEN 5 THEN 'प्रतिष्ठा र नेतृत्व'
