-- संयोजन विश्लेषण (भाव + राशि + ग्रह): स्वास्थ्य र आध्यात्मिक पक्ष
-- ९ ग्रह × १२ भाव × १२ राशि = १२९६ संयोजन
-- ग्रहको शारीरिक क्षेत्र, भावको शरीर-क्षेत्र, राशिको शरीर-क्षेत्र र
-- ग्रहको देवता/आध्यात्मिक स्वरूप आधारित शास्त्रीय सम्बन्धबाट रचित।

ALTER TABLE graha_bhava_rashi
  ADD COLUMN IF NOT EXISTS health_indication mediumtext NULL AFTER relationship_indication,
  ADD COLUMN IF NOT EXISTS spiritual_indication mediumtext NULL AFTER health_indication;

UPDATE graha_bhava_rashi t
JOIN grahas g ON g.id = t.graha_id
JOIN bhavas b ON b.id = t.bhava_id
JOIN rashis r ON r.id = t.rashi_id
SET
  t.health_indication = CONCAT(
    g.name_np, 'को शारीरिक क्षेत्र ',
    CASE t.graha_id
      WHEN 1 THEN 'हृदय, आँखा र हड्डी'
      WHEN 2 THEN 'मन, पाचन र जलात्मक अंग'
      WHEN 3 THEN 'मांसपेशी, रगत र मज्जा'
      WHEN 4 THEN 'स्नायु, छाला र मस्तिष्क'
      WHEN 5 THEN 'कलेजो, वसा र घाँटी'
      WHEN 6 THEN 'मृगौला, कामेन्द्रिय र दृष्टि'
      WHEN 7 THEN 'हड्डी, जोर्नी र दाँत'
      WHEN 8 THEN 'पेट र छाला'
      WHEN 9 THEN 'स्नायु र छाला'
    END,
    ' हो। यो संयोजन ', b.name_np, ' (',
    CASE t.bhava_id
      WHEN 1 THEN 'शीर्ष र समग्र शरीर'
      WHEN 2 THEN 'मुख, दाँत र कण्ठ'
      WHEN 3 THEN 'काँध र हात'
      WHEN 4 THEN 'वक्षस्थल र छाती'
      WHEN 5 THEN 'हृदय र मस्तिष्क'
      WHEN 6 THEN 'पेट र आन्द्राको क्षेत्र'
      WHEN 7 THEN 'कम्मर र मृगौला'
      WHEN 8 THEN 'गुप्त अंग र जननाङ्ग'
      WHEN 9 THEN 'जाँघ'
      WHEN 10 THEN 'घुँडा र ढाडको हड्डी'
      WHEN 11 THEN 'पाख्रा र रगत प्रवाह'
      WHEN 12 THEN 'पाइरा, निद्रा र विश्रान्ति'
    END,
    ') र ', r.name_np, ' राशि (',
    CASE t.rashi_id
      WHEN 1 THEN 'शीर्ष र मस्तिष्क'
      WHEN 2 THEN 'मुख, गला र कण्ठ'
      WHEN 3 THEN 'काँध, हात र फोक्सो'
      WHEN 4 THEN 'वक्षस्थल र पेट'
      WHEN 5 THEN 'हृदय र छातीको पछाडि'
      WHEN 6 THEN 'पेट, आन्द्रा र आँत'
      WHEN 7 THEN 'किडनी र तल्लो ढाड'
      WHEN 8 THEN 'जननाङ्ग र मृगौला'
      WHEN 9 THEN 'जाँघ'
      WHEN 10 THEN 'घुँडा र जोर्नी'
      WHEN 11 THEN 'पाख्रा र टखना'
      WHEN 12 THEN 'पाइरा र लसिका प्रणाली'
    END,
    ') मा केन्द्रित भएर शरीरमा विशेष असर दिन्छ। ',
    CASE t.graha_id
      WHEN 1 THEN 'सूर्य बलिया भएमा रोग प्रतिरोधात्मक शक्ति बढ्छ, कमजोर भएमा आँखा र हृदयमा दबाब पर्छ।'
      WHEN 2 THEN 'चन्द्र शुद्ध भएमा मन शान्त र पाचन ठीक रहन्छ, कमजोर भएमा भावनात्मक खानेबानी र निद्रामा असर पर्छ।'
      WHEN 3 THEN 'मङ्गल तीव्र भएमा ज्वरो, चोट र रगतसम्बन्धी समस्या बढ्छन्, नियन्त्रित भएमा शारीरिक सहनशक्ति बढ्छ।'
      WHEN 4 THEN 'बुध स्थिर भएमा स्नायु र छाला निको रहन्छ, कमजोर भएमा चिन्ता र एलर्जी जस्ता समस्या देखिन्छन्।'
      WHEN 5 THEN 'गुरु शुभ भएमा शरीर सन्तुलित र पाचन शक्ति राम्रो रहन्छ, विशेष गरी वृद्धावस्थामा लाभदायक हुन्छ।'
      WHEN 6 THEN 'शुक्र बलिया भएमा कामेन्द्रिय र दृष्टि निको रहन्छ, कमजोर भएमा मृगौला र जननाङ्गमा समस्या सकिन्छ।'
      WHEN 7 THEN 'शनि कठोर भएमा दीर्घरोग र जोर्नीको पीडा बढ्छ, नियमित दिनचर्याले नियन्त्रण सम्भव छ।'
      WHEN 8 THEN 'राहु अशान्त भएमा अज्ञात रोग र एलर्जी लाग्ने प्रवृत्ति बढ्छ, सन्तुलित भएमा अनुसन्धानमा लाभ हुन्छ।'
      WHEN 9 THEN 'केतु शान्त भएमा चिन्तनले मनोरोग निवारण गर्छ, उद्विग्न भएमा स्नायुगत थकान र भ्रम बढ्छ।'
    END
  ),
  t.spiritual_indication = CONCAT(
    g.name_np, 'को आध्यात्मिक स्वरूप ',
    CASE t.graha_id
      WHEN 1 THEN 'आत्मबोध, पितृसम्मान र ऊर्जाको उपासना'
      WHEN 2 THEN 'मनको शुद्धि, भक्ति र शिवोपासना'
