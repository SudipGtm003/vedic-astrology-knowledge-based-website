      WHEN 9 THEN 'ज्ञान र यात्रा'
      WHEN 10 THEN 'कर्म र उन्नति'
      WHEN 11 THEN 'नवप्रवर्तन र मित्रता'
      WHEN 12 THEN 'करुणा र कल्पना'
    END,
    ' जस्ता क्षेत्रमा श्रद्धापूर्वक लाग्दा त्यसको शुभ फल अधिक हुन्छ।'
  );
