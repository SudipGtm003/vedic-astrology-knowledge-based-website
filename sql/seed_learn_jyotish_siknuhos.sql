केतु महादशा — ७ वर्ष
समग्र दृष्टि
केतु (दक्षिण पात) ले वैराग्य, पूर्व जन्मको पुण्य, अन्तर्ज्ञान, मोक्ष, शुद्धिकारक हानि, एकान्त, र आध्यात्मिक गहिराइ बुझाउँछ। जहाँ राहु भोको हुन्छ, केतुले छोड्न सिकाउँछ। केतु महादशामा अनावश्यक कुराहरू झर्छन् — कहिले बिस्तारै, कहिले पीडासहित — अनि भित्र जहिल्यै रहेको कुरा देखिन्छ।
करियर र वित्त
करियर दिशाहीन लाग्न सक्छ, वा शान्त रूपमा फेरिन्छ। अनुसन्धान, उपचार, चिन्तनात्मक काम, गुप्त/आध्यात्मिक क्षेत्र, आपत्कालीन चिकित्सा, रसायन — उपयुक्त। ‘बाहिरी सफलता’ को बेला होइन — एकीकरण र छोड्ने समय। लामो जागिर अकस्मात छोड्ने सम्भावना।
सम्बन्ध
वैराग्य उठ्छ। लामो सम्बन्ध बिनाकारण अन्त्य हुन सक्छ — वा मौन सहचर्यमा गहिरो। एकान्त बढ्छ। केतु महादशामा विवाह विरलै, भए पनि बलियो आध्यात्मिक/भाग्यपूर्ण भेटपछि।
