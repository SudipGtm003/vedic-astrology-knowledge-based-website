मङ्गल योद्धा हो — साहस, गति, क्रोध, र कर्म-इच्छा। मङ्गलको भावले तपाईं कहाँ लड्नुहुन्छ, धकेल्नुहुन्छ, वा डढ्नुहुन्छ देखाउँछ। राम्रो स्थानमा मङ्गल — एकाग्र साहस र आत्मरक्षा क्षमता; पीडित हुँदा त्यही क्षेत्रमा द्वन्द्व, दुर्घटना, र अप्रशोधित क्रोध। मङ्गलले शारीरिक श्रम, खेलकुद, र एकाग्र कर्ममा ऊर्जा बाहिर निकाल्नेलाई पुरस्कृत गर्छ।
बुध / Mercury
संक्षिप्त परिचय: बुद्धि, वाणी, अध्ययन, व्यापार, चातुर्य
मनोवैज्ञानिक स्वरूप
बुध मनको चपल पाटो हो — वाणी, अध्ययन, हिसाब, हास्य, र सम्पर्क। बुधको भाव त्यो ठाउँ हो जहाँ तपाईं सबभन्दा बढी सोच्नुहुन्छ, बोल्नुहुन्छ, र आदानप्रदान गर्नुहुन्छ। बुध छेउछाउका ग्रहहरूको गुण लिन्छ, त्यसैले एक्लै कमै काम गर्छ। वाणीमा सत्यता र सोचमा अनुशासन — बुधको केन्द्रीय अभ्यास।
बृहस्पति / Jupiter
संक्षिप्त परिचय: ज्ञान, शिक्षक, धर्म, समृद्धि, विस्तार
मनोवैज्ञानिक स्वरूप
गुरु महान् शिक्षक र शुभ ग्रह हो। गुरु जहाँ रहन्छ, त्यहाँ जीवन फैलिन्छ र संरक्षण प्रकट हुन्छ। गुरुको भावमा ज्ञान, श्रद्धा, र सौभाग्य प्राकृतिक रूपमा आउँछन् — साथै यहाँ तपाईंले धेरै कुरा ‘स्वतःसिद्ध’ ठान्ने जोखिम पनि हुन्छ। ज्ञानप्रतिको गर्व विनयको अभावमा बौद्धिक अहंकारमा बदलिन सक्छ।
शुक्र / Venus
संक्षिप्त परिचय: प्रेम, सौन्दर्य, साझेदारी, कला, सुख
मनोवैज्ञानिक स्वरूप
शुक्र प्रेम, कला, सुख, र प्रजनन-शक्तिको प्रतीक। शुक्रको भावमा सौन्दर्य, साझेदारी, र आनन्द खोजिन्छ। यो जीवनको ‘मीठो’ अनुभूति हुने ठाउँ। राम्रो शुक्र — परिष्कृत सम्बन्ध र कलात्मक उपहार; पीडित हुँदा अधूरो सुख, अति-भोग, र प्रेममा अड्किने ढाँचा।
शनि / Saturn
