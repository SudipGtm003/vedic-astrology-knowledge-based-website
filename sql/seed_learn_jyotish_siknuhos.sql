जन्म नक्षत्रको स्वामीले पहिलो महादशा दिन्छ। तर त्यो पूर्ण होइन — जन्म हुँदा त्यस नक्षत्रको कति बाँकी थियो, त्यतिकै महादशा बाँकी रहन्छ। उदाहरण: जन्म हुँदा चन्द्र अश्विनी नक्षत्रमा छ भने पहिलो महादशा केतुको हुन्छ; अश्विनीको आधा बाँकी थियो भने ७ × ½ = ३.५ वर्ष केतुको दशा रहन्छ।
