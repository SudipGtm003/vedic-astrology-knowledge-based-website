स्वास्थ्य
स्नायु प्रणाली (मस्तिष्क-तन्तु), छाला, फोक्सो, वाणी। चिन्ता र ‘धेरै सोच्ने’ ले बुधको दशामा सबभन्दा बढी असर गर्छ। हात-औंलाका समस्या पनि देखिन सक्छन्।
मन र मनोविज्ञान
मन तीव्र, विचार धेरै, शब्द धेरै। ‘सुरु गरेको काम पूरा गर्ने’ अनुशासनले फरक पार्छ। बोलीचालीको शैलीले करियर बनाउँछ। सत्य बोल्ने अभ्यास (बुध वाणीको स्वामी) यस बेला विशेष महत्त्वको हुन्छ।
पढ्ने टिप्स
बुधले साथमा बस्ने ग्रहको गुण लिन्छ — सूर्यसँग बस्दा राजसी, मङ्गलसँग बस्दा तीक्ष्ण/विवादी, शनिसँग बस्दा गम्भीर/अनुसन्धानमुखी।
