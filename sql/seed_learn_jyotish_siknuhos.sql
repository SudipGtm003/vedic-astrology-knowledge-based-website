रहस्यमय रोग, दीर्घ थकान, छाला/कपाल समस्या, मेरुदण्ड। केतु तल्लो शरीरको प्रतीक। ऊर्जा घट्न सक्छ। योग र ध्यान — चिकित्साभन्दा बढी राहत।
