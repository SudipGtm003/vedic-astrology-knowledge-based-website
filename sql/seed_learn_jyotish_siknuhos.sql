बुध महादशा — १७ वर्ष
समग्र दृष्टि
बुधले बुद्धि, वाणी, अध्ययन, व्यापार, लेखन, हिसाब, सञ्चार, र मित्रता बुझाउँछ। बुध महादशा (१७ वर्ष) ‘सोच्ने, बोल्ने, कारोबार गर्ने, मानिसमानिस जोडिने’ अवधि हो। जिज्ञासुलाई पुरस्कार दिने समय।
करियर र वित्त
शिक्षण, लेखन, पत्रकारिता, हिसाब-किताब, सफ्टवेयर, व्यापार, मध्यस्थता, बिक्री — सबै राम्रा। मानिसहरू पुनः अध्ययनमा फर्किन्छन् वा ज्ञानमूलक करियर रोज्छन्। सम्पर्क-वृत्त बढ्छ। आम्दानीका धेरै स्रोत हुनु सामान्य।
सम्बन्ध
