सतही कुराले सन्तुष्टि नदिने अनुभूति। सामाजिक हल्लाबाट टाढिने इच्छा। मनले गहिराइ, मौन, ‘म वास्तवमा को हुँ?’ खोज्छ। पुराना पहिचानहरू गल्छन्। अरूले ‘बदलियो’ वा ‘टाढियो’ ठान्न सक्छन् — तर तपाईं त पुरानो आकार छाडेर अघि बढ्नुभएको हो।
पढ्ने टिप्स
केतुले आध्यात्मिक उन्नति तीव्र बनाउँछ तर भौतिक महत्त्वाकाङ्क्षामा कठोर। कुण्डलीमा केतु ९/१२ मा भए यो दशाले गहिरो ज्ञान दिन्छ; ६/८ मा भए कठिन तर आत्म-शुद्धि गर्ने घटनाहरू।
शुक्र महादशा — २० वर्ष
समग्र दृष्टि
शुक्रले प्रेम, कला, सौन्दर्य, सुख, साझेदारी, सवारी, र विलासिता बुझाउँछ। शुक्र महादशा सबभन्दा लामो (२० वर्ष) — यो भोग, सम्बन्ध, परिष्कार, र ‘अनासक्त भोग’ को अनुशासन सिकाउने समय।
करियर र वित्त
कला, डिजाइन, फेसन, मनोरञ्जन, सौन्दर्य, होटल, खाद्य, कूटनीति, घरजग्गा, वित्त — राम्रा। काम सिर्फ ‘उत्पादक’ नभई ‘रमाइलो लाग्ने’ हुन्छ। ग्राहक र साझेदारसँगको सम्बन्धले अवसर ल्याउँछ।
सम्बन्ध
विवाहको प्रारम्भ, गहन हुने, वा परीक्षा — विशेषतः पुरुषका लागि (शुक्र पत्नीको प्रतीक)। प्रेम-जीवन सजीव। मित्रता, सामाजिक सम्बन्ध, कलात्मक समूह फस्टाउँछन्।
स्वास्थ्य
प्रजनन प्रणाली, मिर्गौला, मूत्रमार्ग, घाँटी, आँखा। मीठो खानेकुराको लोभ — मधुमेह र तौल वृद्धिको जोखिम। शुक्र खुसी हुँदा छाला चम्किन्छ।
मन र मनोविज्ञान
सौन्दर्य र सद्भावप्रति संवेदनशीलता बढ्छ। द्वन्द्व छल्ने प्रवृत्ति — सीमारेखा कोर्न नसक्ने हुन सक्छ। ‘प्रेम जीवनको केन्द्रीय कुरा हो’ जस्तो लाग्ने। छाया-पक्ष: भोग, आरामको लत, गलत साझेदारी छोड्न नसक्ने।
पढ्ने टिप्स
शुक्र ६/८/१२ भावमा पीडित हुन्छ (विशेष ८ मा)। मङ्गलसँग — भावुक तर अशान्त; शनिसँग — परिपक्व/ढिलो खुल्ने; सूर्यसँग — दबिएको।
सूर्य महादशा — ६ वर्ष
समग्र दृष्टि
सूर्यले हाम्रो आत्मा (भित्री ‘म’), बुबा, अधिकार जमाउने क्षमता, र शरीरको ओजलाई बुझाउँछ। सूर्य महादशा सुरु हुँदा ‘मेरो परिचय के हो, मेरो काम के हो’ भन्ने प्रश्न महत्त्वपूर्ण बन्छ। नेतृत्व लिने अवसर, अरूको सम्मान, र आत्मगौरव — यी कुरा यी ६ वर्षमा प्रमुख हुन्छन्। कुण्डलीमा सूर्य राम्रो ठाउँमा छ भने प्रतिष्ठा र देखिने अवसर बढ्छन्; कमजोर वा पीडित छ भने हाकिमसँग ठक्कर, अहम्‌मा चोट, वा बुबासँगका चिन्ता आउन सक्छन्।
करियर र वित्त
अघि सर्ने बेला हो — पदोन्नति, सार्वजनिक भूमिका, ठूलो जिम्मेवारी। मानिसहरू तपाईंलाई नेता बनाउन खोज्छन्। पुरानो कामको कदर हुन्छ। तर सूर्य कमजोर भएमा वरिष्ठहरूसँग टकराव र प्रतिष्ठाको परीक्षा पनि सम्भव।
सम्बन्ध
बुबा र बुबा-तुल्य व्यक्ति मनमा आइरहन्छन् — राम्रो वा गाह्रो जे होस्। विवाह र काममा ‘को मुख्य’ भन्ने कुराको परीक्षा हुन्छ। साथी कम तर भारी हुन्छन् — गहन कुरा गर्न मिल्ने थोरै मानिस।
स्वास्थ्य
मुटु, आँखा (पुरुषमा दायाँ, महिलामा बायाँ बढी), रगत बग्ने नली, हड्डी, बोसो पाचन। आफूलाई धेरै थकाउने प्रवृत्ति बढ्छ — पूरै विश्राम नभए ‘बर्नआउट’ हुन सक्छ।
मन र मनोविज्ञान
‘म को हुँ, मेरो काम के हो’ भन्ने प्रश्न मनमा गहिरो बस्छ। आफैँलाई अनुशासनमा राख्ने रुचि बढ्छ। मान-सम्मानप्रति बढी संवेदनशील — सानो अपमान पनि मनमा गहिरो लाग्छ। ध्यान र आत्म-चिन्तन यस बेला विशेष फलदायी।
पढ्ने टिप्स
कुण्डलीमा सूर्य कुन भाव र राशिमा छ — त्यही जीवन-क्षेत्र यी ६ वर्षभर ‘उज्यालिने’ वा ‘पोल्ने’ हुन्छ। उदाहरणका लागि: सूर्य १० मा भए करियर मुख्य; ७ मा भए विवाह/साझेदारी; ४ मा भए घर र आमासँगको सम्बन्ध।
चन्द्र महादशा — १० वर्ष
समग्र दृष्टि
चन्द्रले हाम्रो मन, भावना, आमा, र साधारण मानिसहरूसँगको सम्बन्ध बुझाउँछ। चन्द्र महादशा भनेको १० वर्षको ‘भावनात्मक मौसम’ हो — घर, परिवार, महिला, र जनसमुदायसँगको सम्बन्धमा गहन प्रभाव पर्ने समय। यस बेला तपाईंको मूड, अन्तर्ज्ञान (भित्री बोध), र संवेदनशीलता बढ्छन्।
करियर र वित्त
मानिसहरूसँग सीधा जोडिने काम राम्रो फस्टाउँछ — बिक्री, होटल/रेस्टुरेन्ट, खाद्य, घरजग्गा, नर्सिङ, शिक्षण, हेरचाह। ‘ठूलो हुने इच्छा’ भन्दा ‘मन मिल्ने काम’ ले अघि बढाउँछ; मनलाई सुहाउने काममा सबभन्दा राम्रो फल।
सम्बन्ध
आमा र आमा-तुल्य व्यक्ति केन्द्रमा। पारिवारिक बन्धन गाढा हुन्छन्। विवाह र साझेदारी भावनात्मक टेकोको स्रोत बन्छन्। महिलाहरूसँगको मित्रता विशेष महत्त्वपूर्ण।
स्वास्थ्य
फोक्सो, पेट, छाती, शरीरका तरल पदार्थ। पानी असन्तुलन, साइनस, चिसो रोग। निद्राको गुणस्तर सामान्यभन्दा बढी महत्त्वपूर्ण; चन्द्र पीडित भए अनिद्रा देखिन सक्छ।
मन र मनोविज्ञान
एक दशक भावनात्मक सिकाइको। मूड परिवर्तन हुनु सामान्य — लड्न पनि नपर्ने, बहकिनु पनि नपर्ने। अन्तर्ज्ञान तीव्र हुन्छ; सपनाले पनि सूचना दिन्छ। पुराना कुराको याद, घरप्रति लगाव, ‘कतै पनि मिलेर बस्ने’ इच्छा बारम्बार आउँछ।
पढ्ने टिप्स
चन्द्रको शक्ति त्यसको ‘कला’ ले निर्धारण हुन्छ — शुक्ल पक्ष/पूर्ण = बलियो; कृष्ण/क्षीण = कमजोर। क्षीण चन्द्रको दशा भावनात्मक रूपमा थकाउने हुन सक्छ — ध्यान, प्रार्थना, परिवारसँगको समय धेरै सहयोगी।
मङ्गल महादशा — ७ वर्ष
समग्र दृष्टि
मङ्गलले कर्म-शक्ति, साहस, क्रोध, भाइ, र ‘बाधा छेद्ने’ शक्ति बुझाउँछ। मङ्गल महादशा छोटो (७ वर्ष) तर तीव्र हुन्छ — यस बेला धेरै कुरा सिद्ध गर्न सकिन्छ; ध्यान नदिए धेरै कुरा डढ्न पनि सक्छन्।
करियर र वित्त
आफ्नो व्यवसाय, कडा शारीरिक काम, खेलकुद, सेना, शल्यक्रिया, इन्जिनियरिङ/आईटी, घरजग्गा कारोबार — यी क्षेत्रमा राम्रो फल। जोखिम लिने उद्यमलाई पुरस्कार — तर अनुशासनसँग मात्र। नभए महँगा गल्ती।
सम्बन्ध
भाइ-दिदी-बहिनी केन्द्रमा। यौन ऊर्जा बढ्छ। साथी, छिमेकी, प्रतिद्वन्द्वीसँग टकराव सम्भव — ‘कहिले लड्ने, कहिले हट्ने’ भन्ने पाठ यो दशाको मुख्य सिकाइ हो।
स्वास्थ्य
रगत, हाडको मज्जा, मांसपेशी, टाउको। दुर्घटना, शल्यक्रिया, ज्वरो, सूजन — सम्भावना बढी। नियमित व्यायाम अनिवार्य; नभए मङ्गलको आगो शरीरभित्रै फर्केर पोल्न थाल्छ।
मन र मनोविज्ञान
छिटो काम, छिटो रिस। धैर्य नै सबभन्दा महत्त्वपूर्ण अभ्यास। साहस लापरबाहीमा फेरिन सक्छ। तर सही ढङ्गले प्रयोग गर्ने हो भने ‘नाइँ’ भन्न सक्ने, आफ्नो समय जोगाउन सक्ने क्षमता खुब बढ्छ।
पढ्ने टिप्स
मङ्गलको भावले ‘आगो कहाँ बल्छ’ बताउँछ। केन्द्र भाव (१/४/७/१०) मा भए महत्त्वाकाङ्क्षा सीधा; त्रिकोण (५/९) मा भए सिर्जनशील; ६ भावमा द्वन्द्वमुखी; ८/१२ मा गहिरो रूपान्तरण ल्याउने।
राहु महादशा — १८ वर्ष
समग्र दृष्टि
राहु (चन्द्रको उत्तर पात) ले महत्त्वाकाङ्क्षा, विदेशी कुरा, मोह, अकस्मात लाभ, जनसमुदाय, प्रविधि, अपरम्परागत, र भित्र दबिएका इच्छा बुझाउँछ। राहु सीधै फल दिँदैन — विस्तार गर्छ, बङ्ग्याउँछ, अनपेक्षित ढङ्गले पुरस्कार दिन्छ। राहु महादशा प्रसिद्ध रूपमा अशान्त र ‘ठूलो परिवर्तन ल्याउने’।
करियर र वित्त
विदेश यात्रा/काम, प्रविधि, सञ्चारमाध्यम, राजनीति, गुप्त विषयको अनुसन्धान, अत्याधुनिक क्षेत्र। अकस्मात उन्नति। अकस्मात पतन। पुराना योजना भग्न। सट्टेबाजी, क्रिप्टो, भाइरल ख्याति — राहुको खेल मैदान। आम्दानी असामान्य ढङ्गले बढ्न सक्छ।
सम्बन्ध
अपरम्परागत साझेदारी सामान्य — फरक संस्कृति, उमेर, पृष्ठभूमि। विवाह अकस्मात वा अनौठो ढङ्गले ढिलो हुन सक्छ। पुरानो मित्रता टुट्छ; पूर्णतः नयाँ वृत्त बन्छ।
स्वास्थ्य
अदृश्य गुनासा, एलर्जी, निदान हुन नसक्ने समस्या, चिन्ता, लत, छाला रोग। राहुले निदान प्रक्रियालाई अल्मल्याउँछ। मानसिक स्वास्थ्यमा विशेष ध्यान चाहिन्छ — अस्थिरता, दौडिने मन, ‘छुट्न डर लाग्ने’ भाव।
मन र मनोविज्ञान
‘के चाहिएको हो’ थाहै नभएको भोक। ‘अझ धेरै’ — दृश्यता, धन, अनौठा अनुभव। छोटो बाटो लिन, अतिशयोक्ति गर्न, अर्को कुरामा हम्किन मन लाग्छ। पाठ: आफ्नो भोकलाई परिपक्व बनाउनुहोस्, ताकि त्यसले तपाईंलाई नचलाओस्।
पढ्ने टिप्स
राहु त्रिकोण (५/९) मा भए भौतिक सफलता; दुस्थान (६/८/१२) मा भए कठिन कर्म हुँदै आध्यात्मिक प्रगति; केन्द्र (१/४/७/१०) मा भए अस्थिर प्रसिद्धि। पहिलो ३-४ र अन्तिम २ वर्ष सबभन्दा अशान्त।
बृहस्पति (गुरु) महादशा — १६ वर्ष
समग्र दृष्टि
गुरुले ज्ञान, शिक्षक, धर्म, विस्तार, समृद्धि, सन्तान, र दर्शन बुझाउँछ — सबभन्दा शुभ ग्रह मानिन्छ। गुरु महादशा (१६ वर्ष) मा जीवन सामान्यतया फैलिन्छ — करियर, परिवार, अध्ययन, साधना। तर ‘तपाईं जे हुनुहुन्छ’ त्यो पनि फैलिन्छ — तौल, अहम्, खराब बानी समेत।
करियर र वित्त
शिक्षण, सल्लाह, कानून, वित्त, अध्यात्म, शिक्षा, प्रकाशन, सरकारी क्षेत्र — सबै राम्रा। पदोन्नति र वरिष्ठहरूले मार्गदर्शन गरेको अनुभूति सामान्य।
सम्बन्ध
विवाह यो दशामा प्रायः हुन्छ (विशेषतः महिलाका लागि — गुरु पतिको प्रतीक)। सन्तानको जन्म वा त्यसको सोच केन्द्रमा। बुबा र गुरु-तुल्य व्यक्तिसँगको सम्बन्ध गहिरो।
स्वास्थ्य
कलेजो, अग्न्याशय (पाचनको ग्रन्थि), बोसो चयापचय, कमर/जाँघ। मधुमेहको जोखिम बढ्न सक्छ। मीठो र आराममा बढी अभ्यस्त हुने सम्भावना।
मन र मनोविज्ञान
आशा, दार्शनिक मन, उदारता। ‘जीवनको अर्थ छ’ भन्ने अनुभूति बढ्छ। बढी प्रतिज्ञा गर्ने प्रवृत्ति। ज्ञानप्रतिको गर्व विनयको अभावमा बौद्धिक अहंकारमा बदलिन सक्छ। आफूभन्दा ठूलो कुरामा (धर्म, सिद्धान्त) विश्वास गहिरो हुन्छ।
पढ्ने टिप्स
गुरुको भावले ‘जीवन कहाँ फैलिन्छ’ देखाउँछ। ७ मा साझेदारी; ५ मा सन्तान/सिर्जना; १० मा सार्वजनिक धर्म/करियर; ११ मा ठूलो लाभ।
शनि महादशा — १९ वर्ष
समग्र दृष्टि
शनिले अनुशासन, श्रम, उमेर, धैर्य, प्रतिबन्ध, र कर्मफल बुझाउँछ। सबभन्दा कठिन तर धैर्यवानलाई दीर्घकालीन फल दिने महादशा। शनिले ढिलो गर्छ ताकि फल टिकाउ होस् — यही दशाको वचन हो।
करियर र वित्त
बिस्तारै चढाइ, छोटो बाटो छैन। निजामती सेवा, कानून, खानी, उत्पादन, श्रमिक संगठन, बूढापाकाको सेवा, घरजग्गा (विशेषतः जग्गा), इन्जिनियरिङ। कदर ढिलो तर पक्का। काम परिवर्तन हुन्छ तर हरेकको तौल बढी।
सम्बन्ध
एकाकीपन प्रायः हुन्छ — सम्बन्ध भारी, जिम्मेवारीले भरिएका, कम चञ्चल। वृद्ध वा टाढाका साझेदार सामान्य। विवाह ढिलो वा कर्तव्य-बद्ध अनुभूति। मित्रता पातलो हुन्छ — तर बाँकी रहेका आजीवन।
स्वास्थ्य
हाड, जोर्नी, घुँडा, दाँत, दीर्घ रोग, स्नायु थकान। शनिले पहिले उपेक्षा गरिएका कुरा सतहमा ल्याउँछ। नियमित विश्राम, सादा खाना, नियमित दिनचर्या — औषधिभन्दा महत्त्वपूर्ण।
मन र मनोविज्ञान
यथार्थवादी सोच — कहिले निराशामुखी पनि। ‘प्रयास नै सच्चा मुद्रा’ भन्ने मान्यता बस्छ। धैर्य बाध्य भएर पनि स्वाभाविक बन्छ। ‘अरूलाई खुसी पार्ने’ प्रवृत्ति घट्छ। दशाको अन्त्यतिर एक मौन अधिकार उत्पन्न हुन्छ — कसैले खोस्न नसक्ने।
